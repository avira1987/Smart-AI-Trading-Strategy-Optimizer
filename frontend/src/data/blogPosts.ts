// ترتیب مقالات بر اساس تاریخ (جدیدترین اول) مرتب می‌شود
export const getBlogPostsArray = (): BlogPost[] => {
  const allKeys = Object.keys(blogPostsData)
  
  // تبدیل به array با استفاده از map
  const postsArray: BlogPost[] = allKeys.map(key => blogPostsData[key]).filter(post => post && post.id && post.slug)
  
  // مرتب‌سازی بر اساس تاریخ (جدیدترین اول)
  return postsArray.sort((a, b) => {
    const dateA = new Date(a.date).getTime()
    const dateB = new Date(b.date).getTime()
    return dateB - dateA // نزولی (جدیدترین اول)
  })
}

